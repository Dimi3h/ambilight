#!/usr/bin/env python3
"""Derive a cell->zone spatial profile for the LG histogram from a walking-white-cell
dump (produced by the probe's zone-mapping pattern) and emit a C header.

usage: gen_profile.py <dump.txt> <out.h>

The pattern: ~12 s black, 2 s full white (sync), 1 s black, then a white cell walks a
16x9 grid, 300 ms per cell. For each grid cell we find which histogram zone responded
most, giving a 16x9 table of "the zone that best represents this screen cell". Cells
with no measurement are filled from the nearest neighbour.
"""
import sys

COLS, ROWS, CELL_MS, LEAD_MS = 16, 9, 300, 3000


def load(path):
    rows = []
    for line in open(path):
        p = line.split()
        if not p or p[0] != "H":
            continue
        t = int(p[1])
        v = [sum(map(int, x.split(":")[1].split(","))) / 3 for x in p[2:]]
        rows.append((t, v))
    return rows


def main():
    rows = load(sys.argv[1])
    # longest run with every zone bright = the white sync flash
    best = run = None
    for t, v in rows:
        if min(v) > 150:
            run = (run[0], t) if run else (t, t)
        else:
            if run and (not best or run[1] - run[0] > best[1] - best[0]):
                best = run
            run = None
    if run and (not best or run[1] - run[0] > best[1] - best[0]):
        best = run
    start = best[0] + LEAD_MS
    # per cell, mean response of each zone while that cell was white
    cell_zone = [[None] * COLS for _ in range(ROWS)]
    for k in range(COLS * ROWS):
        a, b = start + k * CELL_MS + 90, start + (k + 1) * CELL_MS - 60
        samples = [v for t, v in rows if a <= t < b]
        if not samples:
            continue
        resp = [sum(s[z] for s in samples) / len(samples) for z in range(16)]
        base = min(resp)  # subtract the global lift so big zones don't always win
        r, c = divmod(k, COLS)
        cell_zone[r][c] = max(range(16), key=lambda z: resp[z] - base)
    # fill missing cells from nearest measured neighbour (spiral search)
    def nearest(r0, c0):
        for rad in range(1, COLS + ROWS):
            for r in range(max(0, r0 - rad), min(ROWS, r0 + rad + 1)):
                for c in range(max(0, c0 - rad), min(COLS, c0 + rad + 1)):
                    if cell_zone[r][c] is not None:
                        return cell_zone[r][c]
        return 0
    for r in range(ROWS):
        for c in range(COLS):
            if cell_zone[r][c] is None:
                cell_zone[r][c] = nearest(r, c)
    # emit
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by tools/gen_profile.py from phase-1 measurements. Do not edit by hand.\n")
        f.write("// 16x9 grid of screen cells (row-major, top-left origin); value = histogram zone id.\n")
        f.write("#pragma once\n")
        f.write(f"#define PROFILE_COLS {COLS}\n#define PROFILE_ROWS {ROWS}\n")
        f.write("static const unsigned char PROFILE_CELL_ZONE[PROFILE_ROWS][PROFILE_COLS] = {\n")
        for r in range(ROWS):
            f.write("    {" + ", ".join(f"{cell_zone[r][c]:2d}" for c in range(COLS)) + "},\n")
        f.write("};\n")
    print("white sync", best, "cells/zone map:")
    for r in range(ROWS):
        print("  " + " ".join(f"{cell_zone[r][c]:2d}" for c in range(COLS)))


if __name__ == "__main__":
    main()
