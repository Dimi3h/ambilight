typedef struct {
    uint32_t id;
    uint16_t bins[3][256];
} hist_rec_t;
_Static_assert(sizeof(hist_rec_t) == 1540, "histogram record size");

static void* (*h_init)(bool (*)(void));
static int (*h_preset)(void*, int);
static int (*h_get)(void*, void*);
static int (*h_fini)(void*);
static void* g_hist;
static volatile int g_policy;

static bool policy_cb(void)
{
    g_policy++;
    return true;
}

static uint8_t mean_bin(const uint16_t* bins)
{
    uint64_t c = 0, w = 0;
    for (int b = 0; b < 256; b++) {
        c += bins[b];
        w += (uint64_t)bins[b] * b;
    }
    return c ? (uint8_t)((w + c / 2) / c) : 0;
}

#define DEVMODE_PATH "/var/luna/preferences/vt_devmode"

// Create the LG developer gate only for the moment of initHistogram; a guard child
// removes it after 10 s even if we die, and an existing marker owned by someone else
// is left untouched. Mirrors LG's own pattern (see findings doc).
static pid_t devmode_enter(int* gfd)
{
    *gfd = -1;
    int fd = open(DEVMODE_PATH, O_CREAT | O_EXCL | O_WRONLY | O_CLOEXEC, 0600);
    if (fd < 0) return 0; // already present (or cannot create): leave it alone
    struct stat st;
    if (fstat(fd, &st) != 0) { close(fd); unlink(DEVMODE_PATH); return 0; }
    close(fd);
    int p[2];
    if (pipe(p) != 0) { unlink(DEVMODE_PATH); return 0; }
    pid_t c = fork();
    if (c == 0) {
        close(p[1]);
        struct pollfd pf = { p[0], POLLIN | POLLHUP, 0 };
        poll(&pf, 1, 10000);
        struct stat cur;
        if (lstat(DEVMODE_PATH, &cur) == 0 && cur.st_ino == st.st_ino && cur.st_dev == st.st_dev)
            unlink(DEVMODE_PATH);
        _exit(0);
    }
    close(p[0]);
    if (c < 0) { close(p[1]); unlink(DEVMODE_PATH); return 0; }
    *gfd = p[1];
    return c;
}

static void devmode_leave(pid_t guard, int gfd)
{
    if (guard <= 0) return;
    close(gfd);
    waitpid(guard, NULL, 0);
}

static bool hist_load(void)
{
    void* lib = dlopen("libvtcapture.so.1", RTLD_NOW | RTLD_GLOBAL);
    if (!lib) { logmsg("dlopen libvtcapture failed: %s", dlerror()); return false; }
    h_init = dlsym(lib, "vtCapture_initHistogram");
    h_preset = dlsym(lib, "vtCapture_setPresetHistogram");
    h_get = dlsym(lib, "vtCapture_getHistogram");
    h_fini = dlsym(lib, "vtCapture_finalizeHistogram");
    return h_init && h_preset && h_get && h_fini;
}

// Active histogram preset (0 = full frame; 1..3 measured in tools/calibrate.py).
static int g_preset = 0;

static bool hist_open(void)
{
    int gfd;
    pid_t guard = devmode_enter(&gfd);
    g_hist = h_init(policy_cb);
    devmode_leave(guard, gfd);
    if (!g_hist) return false;
    h_preset(g_hist, g_preset);
    return true;
}

static void hist_close(void)
{
    if (g_hist) { h_fini(g_hist); g_hist = NULL; }
}

// Exact (unrounded) zone means of the last successful read, for calibration dumps.
static double g_zf[16][3];
// Fraction of each zone's pixels at or below a few dark thresholds, per channel.
// A black bar is dark in all channels, so min over channels bounds its share.
#define NLOW 4
static const int LOW_T[NLOW] = { 4, 8, 16, 24 };
static double g_zlow[16][3][NLOW];

static double mean_bin_f(const uint16_t* bins)
{
    uint64_t c = 0, w = 0;
    for (int b = 0; b < 256; b++) {
        c += bins[b];
        w += (uint64_t)bins[b] * b;
    }
    return c ? (double)w / (double)c : 0.0;
}

// The TV samples the picture on a 162x91 grid and each zone is a rectangle of it (its bin
// counts add up to columns x rows: 47x31 bottom-left, 97x19 bottom centre, 49x31
// bottom-right, 81x91 for the halves). On YouTube the last row of that grid holds grey
// values that are not on the screen: under a picture with a black lower edge every bottom
// zone had exactly one row of non-black samples (measured 2026-11-12 with --hist-dump),
// which lit the bottom LEDs on dark pictures. For the three zones that only cover the
// bottom, one row's worth of the brightest samples is left out. The totals are checked, so
// a different grid (another model or firmware) switches this off.
static const struct { int zone, total, cols; } LAST_ROW[] = { { 1, 1843, 97 }, { 5, 1457, 47 }, { 9, 1519, 49 } };

static int last_row_cols(int zone, uint32_t total)
{
    for (size_t i = 0; i < sizeof(LAST_ROW) / sizeof(LAST_ROW[0]); i++)
        if (LAST_ROW[i].zone == zone) return (uint32_t)LAST_ROW[i].total == total ? LAST_ROW[i].cols : 0;
    return 0;
}

static void drop_brightest(uint16_t* bins, int n)
{
    for (int b = 255; b > 0 && n > 0; b--) {
        int t = bins[b] < n ? bins[b] : n;
        bins[b] = (uint16_t)(bins[b] - t);
        n -= t;
    }
}

// Zone means and dark shares from one set of histogram records (modifies the records).
static void hist_process(hist_rec_t* buf, uint8_t zrgb[16][3])
{
    for (int i = 0; i < 16; i++) {
        int drop = 0;
        if (g_preset == 0 && !g_keep_last_row) {
            uint32_t n = 0;
            for (int b = 0; b < 256; b++) n += buf[i].bins[0][b];
            drop = last_row_cols(i, n);
        }
        for (int c = 0; c < 3; c++) {
            if (drop) drop_brightest(buf[i].bins[c], drop);
            g_zf[i][c] = mean_bin_f(buf[i].bins[c]);
            zrgb[i][c] = mean_bin(buf[i].bins[c]);
            uint32_t total = 0, cum = 0;
            for (int b = 0; b < 256; b++) total += buf[i].bins[c][b];
            int t = 0;
            for (int b = 0; b <= LOW_T[NLOW - 1]; b++) {
                cum += buf[i].bins[c][b];
                while (t < NLOW && b == LOW_T[t]) g_zlow[i][c][t++] = total ? (double)cum / total : 0;
            }
        }
    }
}

// Read 16 zones into zrgb[16][3]; returns true on success.
