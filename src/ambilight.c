// Read the args file into a word list and apply it. Returns false if it cannot be read.
static bool load_args_file(void)
{
    if (!g_args_path[0]) return false;
    FILE* f = fopen(g_args_path, "r");
    if (!f) return false;
    static char buf[512];
    size_t n = fread(buf, 1, sizeof(buf) - 1, f);
    fclose(f);
    buf[n] = 0;
    char* words[32];
    int argc = 1;
    words[0] = "args";
    for (char* tok = strtok(buf, " \t\r\n"); tok && argc < 32; tok = strtok(NULL, " \t\r\n")) words[argc++] = tok;
    apply_args(argc, words);
    return true;
}

// The status file is only written while someone is watching: `ambilightctl json-status`
