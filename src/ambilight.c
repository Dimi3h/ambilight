// ---------------------------------------------------------------- PNG (dependency-free, stored deflate)

static uint32_t crc32_of(const uint8_t* p, size_t n, uint32_t crc)
{
    crc = ~crc;
    for (size_t i = 0; i < n; i++) {
        crc ^= p[i];
        for (int k = 0; k < 8; k++)
            crc = (crc >> 1) ^ (0xEDB88320u & (-(int32_t)(crc & 1)));
    }
    return ~crc;
}

static uint32_t adler32_of(const uint8_t* p, size_t n)
{
    uint32_t a = 1, b = 0;
    for (size_t i = 0; i < n; i++) {
        a = (a + p[i]) % 65521;
        b = (b + a) % 65521;
    }
    return (b << 16) | a;
}

static void put32(uint8_t* o, uint32_t v)
{
    o[0] = v >> 24; o[1] = v >> 16; o[2] = v >> 8; o[3] = v;
}

// Encode a width*height RGB image (3 bytes/pixel) to a PNG. Returns bytes written.
static size_t png_encode(const uint8_t* rgb, int w, int h, uint8_t* out, size_t out_cap)
{
    // filtered raw = per row: filter byte 0 + RGB
    size_t raw_len = (size_t)h * (1 + (size_t)w * 3);
    uint8_t* raw = malloc(raw_len);
    if (!raw) return 0;
    for (int y = 0; y < h; y++) {
        raw[y * (1 + w * 3)] = 0;
        memcpy(&raw[y * (1 + w * 3) + 1], &rgb[(size_t)y * w * 3], (size_t)w * 3);
    }
    // zlib stream with stored deflate blocks (<=65535 each)
    size_t z_cap = 2 + raw_len + (raw_len / 65535 + 1) * 5 + 4;
    uint8_t* z = malloc(z_cap);
    if (!z) { free(raw); return 0; }
    size_t zn = 0;
    z[zn++] = 0x78; z[zn++] = 0x01;
    size_t off = 0;
    while (off < raw_len) {
        size_t block = raw_len - off;
        if (block > 65535) block = 65535;
        int final = (off + block >= raw_len);
        z[zn++] = final ? 1 : 0;
        z[zn++] = block & 0xff; z[zn++] = (block >> 8) & 0xff;
        uint16_t nlen = ~(uint16_t)block;
        z[zn++] = nlen & 0xff; z[zn++] = (nlen >> 8) & 0xff;
        memcpy(&z[zn], &raw[off], block);
        zn += block;
        off += block;
    }
    put32(&z[zn], 0); // placeholder; adler is big-endian
    uint32_t ad = adler32_of(raw, raw_len);
    z[zn++] = ad >> 24; z[zn++] = ad >> 16; z[zn++] = ad >> 8; z[zn++] = ad;
    free(raw);

    size_t n = 0;
    static const uint8_t sig[8] = { 137, 80, 78, 71, 13, 10, 26, 10 };
    if (out_cap < 8 + 25 + 12 + zn + 12) { free(z); return 0; }
    memcpy(out + n, sig, 8); n += 8;
    // IHDR
    uint8_t ihdr[13];
    put32(ihdr, w); put32(ihdr + 4, h);
    ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0; // 8-bit RGB
    put32(out + n, 13); n += 4;
    memcpy(out + n, "IHDR", 4);
    memcpy(out + n + 4, ihdr, 13);
    put32(out + n + 4 + 13, crc32_of(out + n, 4 + 13, 0));
    n += 4 + 13 + 4;
    // IDAT
    put32(out + n, (uint32_t)zn); n += 4;
    memcpy(out + n, "IDAT", 4);
    memcpy(out + n + 4, z, zn);
    put32(out + n + 4 + zn, crc32_of(out + n, 4 + zn, 0));
    n += 4 + zn + 4;
    free(z);
    // IEND
    put32(out + n, 0); n += 4;
    memcpy(out + n, "IEND", 4);
    put32(out + n + 4, crc32_of(out + n, 4, 0));
    n += 4 + 4;
    return n;
}

static const char B64[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
static size_t base64_encode(const uint8_t* in, size_t n, char* out)
{
    size_t o = 0;
    for (size_t i = 0; i < n; i += 3) {
        uint32_t v = in[i] << 16;
        if (i + 1 < n) v |= in[i + 1] << 8;
        if (i + 2 < n) v |= in[i + 2];
        out[o++] = B64[(v >> 18) & 63];
        out[o++] = B64[(v >> 12) & 63];
        out[o++] = (i + 1 < n) ? B64[(v >> 6) & 63] : '=';
        out[o++] = (i + 2 < n) ? B64[v & 63] : '=';
    }
    out[o] = 0;
    return o;
}

// ---------------------------------------------------------------- HyperHDR JSON client

// The loop must stay responsive (remote key, histogram re-acquire) while HyperHDR is away,
// e.g. the Pi is off: a connect attempt waits at most HH_CONNECT_MS and is repeated only
// every HH_RETRY_MS; a stalled reply costs at most HH_REPLY_MS per frame.
#define HH_CONNECT_MS 300
#define HH_RETRY_MS 3000
#define HH_REPLY_MS 250

static int g_sock = -1;
static uint64_t g_hh_retry_at; // no connect attempt before this time
static enum { HH_NEVER, HH_UP, HH_DOWN } g_hh_state; // to log each change once, not each attempt

static void hh_close(void)
{
    if (g_sock >= 0) { close(g_sock); g_sock = -1; }
}

static void hh_down(const char* why)
{
    hh_close();
    if (g_hh_state != HH_DOWN) logmsg("HyperHDR %s:%d not available (%s); retrying", g_host, g_port, why);
    g_hh_state = HH_DOWN;
}

static bool hh_connect(void)
{
    hh_close();
    uint64_t t = now_ms();
    if (t < g_hh_retry_at) return false;
    g_hh_retry_at = t + HH_RETRY_MS;
    struct sockaddr_in a = { 0 };
    a.sin_family = AF_INET;
    a.sin_port = htons(g_port);
    if (inet_pton(AF_INET, g_host, &a.sin_addr) != 1) {
        struct hostent* he = gethostbyname(g_host); // a name instead of an address: may block on DNS
        if (!he) { hh_down("name not found"); return false; }
        memcpy(&a.sin_addr, he->h_addr_list[0], he->h_length);
    }
    int fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0) return false;
    fcntl(fd, F_SETFL, fcntl(fd, F_GETFL) | O_NONBLOCK);
    int rc = connect(fd, (struct sockaddr*)&a, sizeof(a));
    if (rc != 0 && errno == EINPROGRESS) {
        struct pollfd pf = { fd, POLLOUT, 0 };
        int err = ETIMEDOUT;
        socklen_t len = sizeof(err);
        if (poll(&pf, 1, HH_CONNECT_MS) > 0) getsockopt(fd, SOL_SOCKET, SO_ERROR, &err, &len);
        rc = err ? -1 : 0;
        errno = err;
    }
    if (rc != 0) {
        int e = errno;
        close(fd);
        hh_down(strerror(e));
        return false;
    }
    fcntl(fd, F_SETFL, fcntl(fd, F_GETFL) & ~O_NONBLOCK);
    struct timeval snd = { 1, 0 }, rcv = { 0, HH_REPLY_MS * 1000 };
    setsockopt(fd, SOL_SOCKET, SO_SNDTIMEO, &snd, sizeof(snd));
    setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &rcv, sizeof(rcv));
    int one = 1;
    setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &one, sizeof(one));
    g_sock = fd;
    g_hh_retry_at = 0;
    return true;
}

// Send one command line and read HyperHDR's one-line reply. False if the connection is
// gone or HyperHDR refused the command ("success":false, logged once per connection).
static bool hh_write(const char* buf, size_t n)
{
    static int refused_on = -1;
    size_t off = 0;
    while (off < n) {
        ssize_t w = send(g_sock, buf + off, n - off, MSG_NOSIGNAL);
        if (w <= 0) return false;
        off += (size_t)w;
    }
    char tmp[512];
    ssize_t r = recv(g_sock, tmp, sizeof(tmp) - 1, 0);
    if (r == 0) return false; // closed by HyperHDR
    if (r > 0) {
        tmp[r] = 0;
        if (strstr(tmp, "\"success\":false")) {
            if (refused_on != g_sock) {
                tmp[strcspn(tmp, "\r\n")] = 0;
                logmsg("HyperHDR refused the command: %.200s", tmp);
                refused_on = g_sock;
            }
            return false;
        }
    }
    return true; // a reply that is merely late is not an error
}

// Send a GRID_W x GRID_H RGB image as a PNG JSON image command.
static bool hh_send_image(const uint8_t* rgb, int w, int h)
{
    static uint8_t png[8192];
    size_t pn = png_encode(rgb, w, h, png, sizeof(png));
    if (!pn) return false;
    static char b64[12000];
    base64_encode(png, pn, b64);
    static char msg[14000];
    int mn = snprintf(msg, sizeof(msg),
        "{\"command\":\"image\",\"imagedata\":\"%s\",\"format\":\"auto\","
        "\"priority\":%d,\"duration\":%d,\"origin\":\"ambilight\"}\n",
        b64, g_priority, g_duration_ms);
    if (mn <= 0 || mn >= (int)sizeof(msg)) return false;
    if (g_sock < 0 && !hh_connect()) return false;
    if (!hh_write(msg, (size_t)mn)) {
        hh_down("connection lost or command refused");
        g_hh_retry_at = now_ms() + 1000;
        return false;
    }
    if (g_hh_state != HH_UP) logmsg("HyperHDR connected %s:%d", g_host, g_port);
    g_hh_state = HH_UP;
    return true;
}

static void hh_clear(void)
{
    if (g_sock < 0) return;
    char msg[128];
    int n = snprintf(msg, sizeof(msg), "{\"command\":\"clear\",\"priority\":%d}\n", g_priority);
    hh_write(msg, (size_t)n);
}

